export type IconName = keyof typeof icons;

interface IconProps {
  name: IconName | (string & {});
  className?: string;
}

/** Decorative inline SVG icon. Scales with the surrounding font size by default. */
export default function Icon({ name, className = '' }: IconProps) {
  const Cmp = (icons as Record<string, LucideIcon>)[name];
  if (!Cmp) return null;
  return (
    <Cmp
      aria-hidden="true"
      strokeWidth={2}
      className={`inline-block shrink-0 align-[-0.125em] ${className || 'w-[1.1em] h-[1.1em]'}`}
    />
  );
}
